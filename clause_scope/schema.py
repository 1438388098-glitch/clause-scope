# 中文合同编号条款标题行的常见形式：
#   第一条　合同标的 / 第二条:价款 / 第 3 条 交付与验收 / （一）…（仅条级）
import re

CLAUSE_HEADING_RE = re.compile(
    r"^\s*[（(]?(第[一二三四五六七八九十百千零\d]+条|[0-9一二三四五六七八九十]{1,4}[、.．])[)）]?\s*([^，。；\n]{0,30})?\s*$"
)

CN_NUM = {"一": 1, "二": 2, "三": 3, "四": 4, "五": 5, "六": 6, "七": 7, "八": 8,
          "九": 9, "十": 10}


def cn_to_int(s):
    """中文数字（一到九十九）→ 整数；失败返回 None。"""
    s = (s or "").strip()
    if s.isdigit():
        return int(s)
    if not s:
        return None
    if s == "十":
        return 10
    if "十" in s:
        left, _, right = s.partition("十")
        tens = CN_NUM.get(left, 1) if left else 1
        ones = CN_NUM.get(right, 0) if right else 0
        if (left and left not in CN_NUM) or (right and right not in CN_NUM):
            return None
        return tens * 10 + ones
    return CN_NUM.get(s)
